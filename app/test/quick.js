// Prueba del análisis rápido público: link → análisis → vista de invitado, topes y permisos.
const { spawn } = require('child_process');
const path = require('path'); const fs = require('fs'); const os = require('os');
const { chromium } = require('playwright');
const mocks = require('./mocks');
const OUT = process.env.SHOTS || path.join(os.tmpdir(), 'tita-quick'); fs.mkdirSync(OUT, { recursive: true });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
(async () => {
  const EP = (await import('embedded-postgres')).default;
  const out = []; const log = [];
  const parent = fs.mkdtempSync(path.join(os.tmpdir(), 'pgq-')); fs.chmodSync(parent, 0o777);
  const pg = new EP({ databaseDir: path.join(parent, 'd'), user: 't', password: 't', port: 54333, persistent: false, onLog: () => {}, onError: () => {} });
  await pg.initialise(); await pg.start(); await pg.createDatabase('t');
  const stores = [await mocks.store(4101, 'Propia', 40, -0.08, 0.2), await mocks.store(4102, 'Alfa', 45, 0.05, 0.4), await mocks.store(4103, 'Beta', 40, -0.05, -0.3), await mocks.store(4104, 'Gama', 38, 0.1, 0.8)];
  const api = await mocks.anthropic(4199, log);
  const srv = spawn(process.execPath, ['server/index.js'], { cwd: path.join(__dirname, '..'), env: { ...process.env, PORT: '4310', DATABASE_URL: 'postgres://t:t@localhost:54333/t', ANTHROPIC_API_KEY: 'test', ANTHROPIC_BASE_URL: 'http://127.0.0.1:4199', SESSION_SECRET: 'z'.repeat(40), REFRESH_CRON: 'off', CRAWLER_DELAY_MS: '10', QUICK_PER_IP_DAY: '3' } });
  srv.stderr.on('data', (d) => process.stdout.write('[srv!] ' + d));
  await sleep(2500);
  const b = await chromium.launch(); const page = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage(); page.setDefaultTimeout(20000);
  page.on('pageerror', (e) => out.push('PAGEERR ' + e.message));
  const step = async (n, fn) => { try { await fn(); } catch (e) { out.push('STEP ' + n + ': ' + e.message.split('\n')[0]); await page.screenshot({ path: path.join(OUT, 'fail-' + n.replace(/\W+/g, '_') + '.png') }).catch(() => {}); } };
  await page.goto('http://localhost:4310/');
  await step('landing', () => page.waitForSelector('text=Descubre oportunidades de rentabilidad'));
  await page.screenshot({ path: path.join(OUT, 'q1-landing.png') });
  await step('submit', async () => { await page.fill('#q-url', 'http://127.0.0.1:4101'); await page.click('button:has-text("Analizar")'); await page.waitForSelector('text=Analizando'); });
  await sleep(2500); await page.screenshot({ path: path.join(OUT, 'q2-progress.png') });
  await step('done', () => page.waitForSelector('text=¿Qué está pasando con tus precios?', { timeout: 90000 }));
  await page.screenshot({ path: path.join(OUT, 'q3-overview.png') });
  out.push('guest nav: ' + (await page.locator('.side nav').innerText().catch(() => '')).replace(/\n+/g, ' | '));
  await step('market', async () => { await page.click('.side >> text=Market Intelligence'); await page.waitForTimeout(600); });
  await page.screenshot({ path: path.join(OUT, 'q4-market.png') });
  const checks = await page.evaluate(async () => {
    const me = await (await fetch('/api/me')).json();
    const org = me.org.id;
    const w = await fetch('/api/orgs/' + org + '/docs/cats/x', { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: '{"a":1}' });
    const a = await fetch('/api/orgs/' + org + '/docs/approvals/x', { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: '{"a":1}' });
    const j = await fetch('/api/orgs/' + org + '/ai/json', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{"prompt":"x","kind":"image"}' });
    const adm = await fetch('/api/admin/orgs'); const other = await fetch('/api/orgs/otra/docs');
    return { guest: me.user.guest, codes: [w.status, a.status, j.status, adm.status, other.status] };
  });
  out.push('guest checks: ' + JSON.stringify(checks));
  const tok = await page.evaluate(() => Object.entries(localStorage).find(([k]) => k.startsWith('tita-quick-'))?.[1]);
  const p2 = await (await b.newContext()).newPage();
  await step('shared link', async () => { await p2.goto('http://localhost:4310/?analisis=' + tok); await p2.waitForSelector('text=¿Qué está pasando con tus precios?', { timeout: 20000 }); });
  // Sin competidores legibles: segunda búsqueda y luego se piden al usuario
  mocks.anthropic.noComps = true;
  const p3 = await (await b.newContext()).newPage(); p3.setDefaultTimeout(20000);
  await step('no comps', async () => {
    await p3.goto('http://localhost:4310/'); await p3.fill('#q-url', 'http://127.0.0.1:4104'); await p3.click('button:has-text("Analizar")');
    await p3.waitForSelector('text=¿Quiénes son tus competidores?', { timeout: 60000 });
    await p3.screenshot({ path: path.join(OUT, 'q5-askcomps.png') });
    await p3.fill('#qc-u', 'http://127.0.0.1:4102\nhttp://127.0.0.1:4103'); await p3.click('button:has-text("Continuar con estos competidores")');
    await p3.waitForSelector('text=¿Qué está pasando con tus precios?', { timeout: 90000 });
  });
  out.push('no-comps searches: ' + log.filter((l) => l.search === 'nocomps').length);
  const lim = await page.evaluate(async () => { const r = []; for (let i = 0; i < 2; i++) { const x = await fetch('/api/quick', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ url: 'http://127.0.0.1:4102' }) }); r.push(x.status); } return r; });
  out.push('rate limit (3/día, 2 usados): ' + lim.join(','));
  out.push('claude calls: ' + log.length + ' · web_search: ' + log.filter((l) => l.tools && l.tools > 0).length);
  console.log(out.join('\n'));
  await b.close(); srv.kill(); stores.forEach((s) => s.close()); api.close(); await pg.stop(); process.exit(0);
})().catch((e) => { console.error(e); process.exit(1); });
